#!/usr/bin/env python3
"""Build the per-sandbox SQL injection checker without embedding plaintext flags.

The CyberRange provisioning role runs this script as root.  Flags are read from a
root-only JSON file, XOR-masked with a fresh random key in a generated header, and
the temporary build directory is removed before this process exits.
"""

from __future__ import annotations

import argparse
import grp
import json
import os
from pathlib import Path
import pwd
import secrets
import stat
import subprocess
import sys
import tempfile


FLAG_KEYS = tuple(f"flag_task{number}" for number in range(1, 5))
MASK_KEY_LENGTH = 32
MAX_FLAG_BYTES = 128


def parse_args() -> argparse.Namespace:
    here = Path(__file__).resolve().parent
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--flags-file", type=Path, required=True)
    parser.add_argument("--source", type=Path, default=here / "sqllab.c")
    parser.add_argument("--output", type=Path, default=Path("/usr/local/bin/sqllab"))
    parser.add_argument("--owner", default="root")
    parser.add_argument("--group", default="root")
    parser.add_argument("--cc", default=os.environ.get("CC", "gcc"))
    parser.add_argument(
        "--defense-source",
        default="/home/seed/lab/defense/unsafe.php",
        help="absolute path checked by task 4 in the provisioned VM",
    )
    return parser.parse_args()


def load_flags(path: Path) -> list[bytes]:
    try:
        with path.open(encoding="utf-8") as stream:
            document = json.load(stream)
    except (OSError, UnicodeError, json.JSONDecodeError) as error:
        raise ValueError(f"cannot read the flags file: {error}") from error

    flags: list[bytes] = []
    for key in FLAG_KEYS:
        value = document.get(key) if isinstance(document, dict) else None
        if not isinstance(value, str):
            raise ValueError(f"{key} must be a string")
        encoded = value.encode("utf-8")
        if not (1 <= len(encoded) <= MAX_FLAG_BYTES):
            raise ValueError(f"{key} must contain 1 to {MAX_FLAG_BYTES} UTF-8 bytes")
        if b"\0" in encoded or any(byte < 0x20 or byte == 0x7F for byte in encoded):
            raise ValueError(f"{key} contains a control character")
        flags.append(encoded)
    if len(set(flags)) != len(flags):
        raise ValueError("the four flags must be distinct")
    return flags


def c_bytes(data: bytes) -> str:
    return ", ".join(f"0x{byte:02x}" for byte in data)


def mask_flag(flag: bytes, key: bytes, offset: int) -> bytes:
    return bytes(
        byte
        ^ key[(position + offset) % len(key)]
        ^ ((0xA5 + position * 29 + offset * 17) & 0xFF)
        for position, byte in enumerate(flag)
    )


def write_header(path: Path, flags: list[bytes]) -> None:
    key = secrets.token_bytes(MASK_KEY_LENGTH)
    offsets = [secrets.randbelow(256) for _ in flags]
    lines = [
        "/* Generated by build_checker.py; deleted after compilation. */",
        "#ifndef SQLLAB_GENERATED_FLAGS_H",
        "#define SQLLAB_GENERATED_FLAGS_H",
        f"static const unsigned char SQLLAB_MASK_KEY[{len(key)}] = {{{c_bytes(key)}}};",
    ]
    for number, (flag, offset) in enumerate(zip(flags, offsets), start=1):
        masked = mask_flag(flag, key, offset)
        lines.extend(
            [
                f"static const unsigned char SQLLAB_FLAG_{number}[{len(masked)}] = {{{c_bytes(masked)}}};",
                f"#define SQLLAB_FLAG_{number}_LEN {len(masked)}u",
                f"#define SQLLAB_FLAG_{number}_OFFSET {offset}u",
            ]
        )
    lines.extend(["#endif", ""])
    path.write_text("\n".join(lines), encoding="ascii")
    path.chmod(0o600)


def resolve_identity(owner: str, group: str) -> tuple[int, int]:
    try:
        uid = pwd.getpwnam(owner).pw_uid
    except KeyError as error:
        raise ValueError(f"unknown owner: {owner}") from error
    try:
        gid = grp.getgrnam(group).gr_gid
    except KeyError as error:
        raise ValueError(f"unknown group: {group}") from error
    return uid, gid


def compile_checker(args: argparse.Namespace, flags: list[bytes]) -> None:
    source = args.source.resolve()
    output = args.output.resolve()
    if not source.is_file():
        raise ValueError(f"checker source does not exist: {source}")
    if not os.path.isabs(args.defense_source):
        raise ValueError("--defense-source must be an absolute path")

    uid, gid = resolve_identity(args.owner, args.group)
    output.parent.mkdir(parents=True, exist_ok=True)

    with tempfile.TemporaryDirectory(prefix=".sqllab-build-", dir=output.parent) as directory:
        build_dir = Path(directory)
        header = build_dir / "flags.h"
        candidate = build_dir / "sqllab"
        write_header(header, flags)

        defense_define = f'-DSQLLAB_DEFENSE_SOURCE="{args.defense_source}"'
        command = [
            args.cc,
            "-std=c11",
            "-O2",
            "-Wall",
            "-Wextra",
            "-Werror",
            "-Wformat=2",
            "-Wconversion",
            "-Wshadow",
            "-D_FORTIFY_SOURCE=2",
            "-fstack-protector-strong",
            "-fPIE",
            "-pie",
            "-Wl,-z,relro,-z,now",
            "-Wl,-s",
            defense_define,
            f"-I{build_dir}",
            str(source),
            "-o",
            str(candidate),
            "-lcurl",
            "-lcrypto",
        ]
        try:
            result = subprocess.run(command, check=True, text=True, capture_output=True)
        except FileNotFoundError as error:
            raise ValueError(f"compiler not found: {args.cc}") from error
        except subprocess.CalledProcessError as error:
            if error.stdout:
                print(error.stdout, file=sys.stderr, end="")
            if error.stderr:
                print(error.stderr, file=sys.stderr, end="")
            raise ValueError("checker compilation failed") from error
        if result.stderr:
            print(result.stderr, file=sys.stderr, end="")

        binary = candidate.read_bytes()
        if any(flag in binary for flag in flags):
            raise ValueError("a plaintext flag was found in the compiled checker")

        current = candidate.stat()
        if current.st_uid != uid or current.st_gid != gid:
            try:
                os.chown(candidate, uid, gid)
            except PermissionError as error:
                raise ValueError(
                    f"cannot set checker ownership to {args.owner}:{args.group}; run as root"
                ) from error
        # Secure-exec is required so the dynamic loader discards LD_PRELOAD and
        # related variables before main().  The checker immediately clears its
        # environment and irrevocably drops back to the invoking student's IDs.
        candidate.chmod(0o4711)
        os.replace(candidate, output)

    metadata = output.stat()
    if stat.S_IMODE(metadata.st_mode) != 0o4711 or metadata.st_uid != uid or metadata.st_gid != gid:
        raise ValueError("checker permissions or ownership are incorrect after installation")


def main() -> int:
    args = parse_args()
    try:
        flags = load_flags(args.flags_file)
        compile_checker(args, flags)
    except ValueError as error:
        print(f"build_checker.py: {error}", file=sys.stderr)
        return 1
    print(f"Installed execute-only checker at {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
